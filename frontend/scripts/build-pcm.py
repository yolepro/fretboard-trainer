#!/usr/bin/env python3
"""Builds src/audio/pcm.native.ts: the guitar samples and claves as raw PCM (22 050 Hz, mono, 16-bit, base64),
so iOS and Android can mix a whole sequence ahead of time into one sound file (see src/audio/render.ts).
Run from frontend/: python3 scripts/build-pcm.py   (needs ffmpeg)."""
import base64, os, subprocess, struct

RATE = 22050
NOTE_SEC = 1.6  # a note never rings longer than this in a sequence (the next one stops it)
FADE_SEC = 0.12
NAMES = {40: "E2", 41: "F2", 42: "Fs2", 43: "G2", 44: "Gs2", 45: "A2", 46: "As2", 47: "B2", 48: "C3", 49: "Cs3", 50: "D3", 51: "Ds3",
         52: "E3", 53: "F3", 54: "Fs3", 55: "G3", 56: "Gs3", 57: "A3", 58: "As3", 59: "B3", 60: "C4", 61: "Cs4", 62: "D4", 63: "Ds4",
         64: "E4", 65: "F4", 66: "Fs4", 67: "G4", 68: "Gs4", 69: "A4", 70: "As4", 71: "B4", 72: "C5", 73: "Cs5", 74: "D5"}

def pcm(path, max_sec=None):
    raw = subprocess.run(["ffmpeg", "-v", "error", "-i", path, "-ac", "1", "-ar", str(RATE), "-f", "s16le", "-"], capture_output=True, check=True).stdout
    n = len(raw) // 2
    vals = list(struct.unpack(f"<{n}h", raw))
    # Drop the encoder's leading silence so the note starts on its time.
    start = next((i for i, v in enumerate(vals) if abs(v) > 300), 0)
    vals = vals[max(0, start - 20):]
    if max_sec:
        vals = vals[: int(max_sec * RATE)]
        f = int(FADE_SEC * RATE)
        for i in range(min(f, len(vals))):
            k = len(vals) - 1 - i
            vals[k] = int(vals[k] * i / f)
    return base64.b64encode(struct.pack(f"<{len(vals)}h", *vals)).decode()

out = ["// Generated by scripts/build-pcm.py — do not edit. Samples as base64 PCM (22 050 Hz, mono, 16-bit little-endian).",
       f"export const PCM_RATE = {RATE};", "export const NOTES: Record<number, string> = {"]
for m, name in NAMES.items():
    out.append(f'  {m}: "{pcm(f"assets/sounds/{name}.mp3", NOTE_SEC)}",')
out.append("};")
out.append(f'export const CLAVE_HIGH = "{pcm("assets/sounds/clave_high.wav")}";')
out.append(f'export const CLAVE_LOW = "{pcm("assets/sounds/clave_low.wav")}";')
open("src/audio/pcm.native.ts", "w").write("\n".join(out) + "\n")
print(os.path.getsize("src/audio/pcm.native.ts"))
